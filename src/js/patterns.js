// Пульс-опросы новичков: первая неделя, месяц, испытательный срок, встречи «Хранитель»
export const NOTIF_SURVEY_RE = /пульс-опрос/i;

// Тег уведомления (поле notify_tag в REST), по которому видно, что оно про одну конкретную задачу:
// «TASKS|COMMENT|123456|42|7654321», «TASKS|TASK|123456|42», «RATING|TASK|123456»,
// «SUPPORT_LK|TASK|123456», «ROBOT|TASKS|…\TASK|123456|хеш». Группа 1 — ID задачи. Тег сразу по
// нескольким задачам («TASKS|TASKS|1:2:3|730») сюда не попадает
export const NOTIF_TASK_TAG_RE = /^(?:TASKS\|[A-Z_]+|RATING\|TASK|SUPPORT_LK\|TASK|ROBOT\|TASKS\|[^|]+)\|(\d+)(?:\||$)/;
// Тег сводки дедлайнов: «PX_DEADLINE_TODAY|42|01.01.2026», «PX_DEADLINE_2DAY|…»
export const NOTIF_DEADLINE_TAG_RE = /^PX_DEADLINE_/;

// В напоминании о сделке «[#5123]» — номер сделки, а не задачи (см. NOTIF_TASK_ID_RE). Во всплывающем
// уведомлении строки склеены без переноса, поэтому между двоеточием и номером может не быть ничего
export const NOTIF_DEAL_ID_RE = /напоминание о сделке:\s*\[#(\d+)\]/i;

// Исполнитель в тексте уведомления о новой задаче: "Исполнитель: Фамилия Имя". Берём всё до следующего
// поля или переноса — в баллоне строки склеены без переноса ("…АлександрСоисполнители: …"), а имя
// бывает двойным, латиницей и т.п. «Соисполнители:» сюда не попадает: регистр и окончание другие
export const NOTIF_NEW_TASK_RESPONSIBLE_RE = /Исполнитель:\s*(.+?)(?=Соисполнители:|Наблюдатели:|Постановщик:|\n|$)/;

// Bitrix упоминает ID задачи в тексте уведомления как "[#481203]" — используется, когда в самом
// уведомлении нет ссылки на задачу (всплывающий тост .ui-notification-manager-browser-balloon)
export const NOTIF_TASK_ID_RE = /\[#(\d+)\]/;

// Отдельного атрибута с ID уведомления у всплывающего уведомления нет: он зашит в id вспомогательных
// элементов внутри него (кнопка «Ответить», поле ответа) как "…-im_notify-31857799u1F9D…"
export const NOTIF_BALLOON_ID_RE = /im_notify-(\d+)/;

// call-notifications: время регулярной встречи, "ЧЧ:ММ" в сутках. Маска поля гарантирует только
// цифры на своих местах, поэтому диапазон часов/минут проверяется этим шаблоном — им же валидируется
// импорт встреч из JSON, где никакой маски не было вовсе
export const MEETING_TIME_RE = /^([01]\d|2[0-3]):[0-5]\d$/;
