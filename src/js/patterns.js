export const TAGALL_NAMED_RE = new RegExp(`(?:${PERSON_NAME_SOURCE} )?${TAGALL_PHRASE_RE.source}`, 'g');

// Канонический токен, на который заменяется tagall-фраза (TAGALL_NAMED_RE) перед детекцией —
